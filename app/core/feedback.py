def get_issue_type(key: str) -> IssueType:
    for kind in ISSUE_TYPES:
        if kind.key == key:
            return kind
    raise ValueError(f"Неизвестный тип обращения: {key}")


def issue_markdown(key: str, *, version: str = APP_VERSION) -> str:
    """Генерирует редактируемый текст без приватных данных и логов."""
    issue_type = get_issue_type(key)
    blocks = [f"## {heading}\n{hint}" for heading, hint in issue_type.sections]
    blocks.append(f"## Окружение\n- Мультифора: {version}\n- Windows: [укажите версию]")
    blocks.append(
        "⚠️ Перед публикацией удалите пароли, персональные данные "
        "и конфиденциальные пути или содержимое файлов."
    )
    return "\n\n".join(blocks)


def issue_clipboard_text(title: str, details: str) -> str:
    """Формат для ручной вставки в два поля формы GitFlic."""
    return f"Название:\n{title.strip()}\n\nОписание (Markdown):\n{details.strip()}"
