"""Общие ограничения времени для локальных движков обработки файлов."""

_MIB = 1024 * 1024


def adaptive_timeout(total_bytes: int) -> int:
    """Даёт большим документам больше времени, ограничивая ожидание 10 минутами."""
    size = max(0, total_bytes)
    return min(600, 120 + (size // (8 * _MIB)) * 60)
